#!/usr/bin/env python3
"""Compare two repository runs (reference vs clean-clone candidate).

Numeric determinism check for task T12: compares the outputs of a candidate
copy (fresh environment rerun) against the reference run, with an explicit
whitelist of ENVIRONMENT-DEPENDENT fields that are excluded from identity:

  time_s, ripser_time_s, stage_times_s, build_time_s, generate,
  mapper_build, verification (platform report), pip_freeze.txt

Everything else must match exactly:
  * results/e1/data/*.npy          — point clouds (array equality)
  * results/e1/*_ph_dgms.npz       — ripser diagrams (array equality)
  * results/e1/*_mapper_memberships.json
  * results/e1/e1_audit.json       — scoped JSON compare (whitelist above)
  * results/e1/layout_overlap.json — layout overlap statistics
  * results/e2/e2_sensitivity.json — scoped JSON compare (whitelist above)
  * results/e2/e2_sensitivity.csv  — all columns EXCEPT time_s
  * results/e2/e2_blob_sanity.json — scoped JSON compare
  * audit/glue_code_accounting.json
  * results/e3/inspection_summary.json — scoped JSON compare (generated
    from the authored inspection record, which is rsync-copied verbatim
    and NOT regenerated by the candidate)
  * e3_inspection/stimulus_manifest.json — scoped JSON compare
    (generated_utc whitelisted as environment-dependent)
  * e3_inspection/scoring_key.csv + inspection_worksheet_BLANK.csv —
    CSV compare (all columns)
  * figures/e1/*.html              — byte comparison
  * figures/**/*.png + e3_inspection/stimuli/*.png — PIXEL comparison
    (rendering reproducibility; reported separately, not part of the
    numeric gate)

Output: results/repro/comparison_report.json; exit 0 iff all structural
(numeric/JSON/array) outputs are identical.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent

ENV_DEPENDENT_KEYS = {"time_s", "ripser_time_s", "stage_times_s",
                      "build_time_s", "generate", "ripser", "mapper_build",
                      "generated_utc"}


def scoped_equal(a, b, path: str, diffs: list) -> bool:
    """Recursive equality with the environment-dependent key whitelist."""
    if isinstance(a, dict) and isinstance(b, dict):
        ok = True
        for k in sorted(set(a) | set(b)):
            if k in ENV_DEPENDENT_KEYS:
                continue
            if k not in a or k not in b:
                diffs.append(f"{path}.{k}: present in "
                             f"{'candidate' if k in b else 'reference'} only")
                ok = False
            elif not scoped_equal(a[k], b[k], f"{path}.{k}", diffs):
                ok = False
        return ok
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            diffs.append(f"{path}: list length {len(a)} vs {len(b)}")
            return False
        return all(scoped_equal(x, y, f"{path}[{i}]", diffs)
                   for i, (x, y) in enumerate(zip(a, b)))
    if a != b and not (a is None and b is None):
        diffs.append(f"{path}: {a!r} != {b!r}")
        return False
    return True


def compare_json(path_rel: str, ref: Path, cand: Path, diffs: list) -> dict:
    rj, cj = ref / path_rel, cand / path_rel
    if not rj.exists() or not cj.exists():
        return {"artifact": path_rel, "identical": False,
                "error": "missing file",
                "detail": f"reference={rj.exists()} candidate={cj.exists()}"}
    local: list[str] = []
    same = scoped_equal(json.loads(rj.read_text()), json.loads(cj.read_text()),
                        path_rel, local)
    diffs.extend(local)
    return {"artifact": path_rel, "identical": same,
            "n_differences": len(local),
            "differences": local[:20]}


def compare_array_file(path_rel: str, ref: Path, cand: Path,
                       diffs: list) -> dict:
    ra, ca = ref / path_rel, cand / path_rel
    if not ra.exists() or not ca.exists():
        return {"artifact": path_rel, "identical": False, "error": "missing"}
    if path_rel.endswith(".npy"):
        a, b = np.load(ra), np.load(ca)
        same = a.shape == b.shape and np.array_equal(a, b)
    else:  # .npz
        za, zb = np.load(ra), np.load(ca)
        same = (set(za.files) == set(zb.files)
                and all(np.array_equal(za[k], zb[k]) for k in za.files))
    if not same:
        diffs.append(f"{path_rel}: arrays differ")
    return {"artifact": path_rel, "identical": bool(same)}


def compare_csv(path_rel: str, ref: Path, cand: Path, diffs: list,
                skip_cols: set[str]) -> dict:
    rp, cp = ref / path_rel, cand / path_rel
    if not rp.exists() or not cp.exists():
        return {"artifact": path_rel, "identical": False, "error": "missing"}
    def read_rows(p: Path):
        with open(p) as fh:
            return [r for r in csv.DictReader(
                ln for ln in fh if not ln.startswith("#"))]
    rows_r, rows_c = read_rows(rp), read_rows(cp)
    same = len(rows_r) == len(rows_c)
    if same:
        for i, (rr, rc) in enumerate(zip(rows_r, rows_c)):
            for k in rr:
                if k in skip_cols:
                    continue
                if rr[k] != rc.get(k):
                    diffs.append(f"{path_rel} row{i} col {k}: "
                                 f"{rr[k]} != {rc.get(k)}")
                    same = False
    else:
        diffs.append(f"{path_rel}: row count {len(rows_r)} vs {len(rows_c)}")
    return {"artifact": path_rel, "identical": same,
            "rows_compared": len(rows_r), "columns_skipped": sorted(skip_cols)}


def compare_bytes(path_rel: str, ref: Path, cand: Path, diffs: list) -> dict:
    rp, cp = ref / path_rel, cand / path_rel
    if not rp.exists() or not cp.exists():
        return {"artifact": path_rel, "identical": False, "error": "missing"}
    same = rp.read_bytes() == cp.read_bytes()
    if not same:
        diffs.append(f"{path_rel}: bytes differ")
    return {"artifact": path_rel, "identical": same}


def compare_png_pixel(path_rel: str, ref: Path, cand: Path) -> dict:
    rp, cp = ref / path_rel, cand / path_rel
    if not rp.exists() or not cp.exists():
        return {"artifact": path_rel, "error": "missing"}
    from PIL import Image
    with Image.open(rp) as im1, Image.open(cp) as im2:
        a1 = np.asarray(im1.convert("RGB"), dtype=np.int16)
        a2 = np.asarray(im2.convert("RGB"), dtype=np.int16)
    if a1.shape != a2.shape:
        return {"artifact": path_rel, "pixel_identical": False,
                "error": f"shape {a1.shape} vs {a2.shape}"}
    d = np.abs(a1 - a2)
    return {"artifact": path_rel,
            "pixel_identical": bool(d.max() == 0),
            "max_channel_diff": int(d.max()),
            "mean_abs_diff": round(float(d.mean()), 6),
            "fraction_pixels_differing": round(
                float((d.max(axis=2) > 0).mean()), 8)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--reference", default=str(REPO),
                    help="reference repository root (default: this repo)")
    ap.add_argument("--candidate", required=True,
                    help="candidate (clean-clone) repository root")
    ap.add_argument("--out", default=str(REPO / "results" / "repro" /
                                         "comparison_report.json"))
    args = ap.parse_args()
    ref, cand = Path(args.reference).resolve(), Path(args.candidate).resolve()

    comparisons: list[dict] = []
    diffs: list[str] = []

    # E1 arrays + diagrams + memberships
    for f in sorted((ref / "results" / "e1" / "data").glob("*.npy")):
        comparisons.append(compare_array_file(
            f"results/e1/data/{f.name}", ref, cand, diffs))
    for f in sorted((ref / "results" / "e1").glob("*_ph_dgms.npz")):
        comparisons.append(compare_array_file(
            f"results/e1/{f.name}", ref, cand, diffs))
    for f in sorted((ref / "results" / "e1").glob("*_mapper_memberships.json")):
        comparisons.append(compare_json(
            f"results/e1/{f.name}", ref, cand, diffs))

    comparisons.append(compare_json("results/e1/e1_audit.json", ref, cand, diffs))
    comparisons.append(compare_json("results/e1/layout_overlap.json",
                                    ref, cand, diffs))
    comparisons.append(compare_json("results/e2/e2_sensitivity.json",
                                    ref, cand, diffs))
    comparisons.append(compare_json("results/e2/e2_blob_sanity.json",
                                    ref, cand, diffs))
    comparisons.append(compare_csv("results/e2/e2_sensitivity.csv",
                                   ref, cand, diffs, skip_cols={"time_s"}))
    comparisons.append(compare_json("audit/glue_code_accounting.json",
                                    ref, cand, diffs))
    # E3: generated materials (the authored record rides along via rsync
    # and is deliberately NOT compared as a regenerated output; the summary
    # IS regenerated from it by the candidate's analyzer run)
    comparisons.append(compare_json("e3_inspection/stimulus_manifest.json",
                                    ref, cand, diffs))
    comparisons.append(compare_csv("e3_inspection/scoring_key.csv",
                                   ref, cand, diffs, skip_cols=set()))
    comparisons.append(compare_csv(
        "e3_inspection/inspection_worksheet_BLANK.csv",
        ref, cand, diffs, skip_cols=set()))
    comparisons.append(compare_json("results/e3/inspection_summary.json",
                                    ref, cand, diffs))
    for f in sorted((ref / "figures" / "e1").glob("*_mapper.html")):
        comparisons.append(compare_bytes(f"figures/e1/{f.name}", ref, cand, diffs))

    # figures: pixel-level (rendering reproducibility; NOT part of the gate)
    png_reports = []
    for sub in ("e1", "e2"):
        for f in sorted((ref / "figures" / sub).glob("*.png")):
            png_reports.append(compare_png_pixel(f"figures/{sub}/{f.name}",
                                                 ref, cand))
    for f in sorted((ref / "e3_inspection" / "stimuli").glob("*.png")):
        png_reports.append(compare_png_pixel(
            f"e3_inspection/stimuli/{f.name}", ref, cand))

    all_identical = all(c.get("identical", False) for c in comparisons)
    png_identical = [p for p in png_reports if p.get("pixel_identical")]
    report = {
        "meta": {
            "generated_utc": datetime.now(timezone.utc).isoformat(),
            "reference_root": str(ref),
            "candidate_root": str(cand),
            "excluded_env_dependent_keys": sorted(ENV_DEPENDENT_KEYS),
            "gate": "all structural (array/JSON/CSV-except-time_s) outputs "
                    "identical; PNG figures compared pixel-wise separately",
        },
        "comparisons": comparisons,
        "all_structural_outputs_identical": all_identical,
        "figure_pixel_comparison": {
            "n_figures": len(png_reports),
            "n_pixel_identical": len(png_identical),
            "reports": png_reports,
        },
        "differences": diffs[:50],
        "n_differences_total": len(diffs),
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2))

    print(f"Structural outputs identical: {all_identical} "
          f"({sum(c.get('identical', False) for c in comparisons)}/"
          f"{len(comparisons)} artifacts)")
    print(f"Figures pixel-identical: {len(png_identical)}/{len(png_reports)}")
    if diffs:
        print(f"DIFFERENCES ({len(diffs)}):")
        for d in diffs[:20]:
            print(f"  - {d}")
    print(f"Wrote {out}")
    return 0 if all_identical else 1


if __name__ == "__main__":
    sys.exit(main())
